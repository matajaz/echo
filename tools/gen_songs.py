#!/usr/bin/env python3
"""Convert robsoncouto/arduino-songs .ino melodies -> echo audio_note_t arrays.

Fetches selected songs, parses `int tempo` + `int melody[] = { NOTE, divider, ...}`
(NOTE_X #defines resolve to a frequency in Hz; REST=0), computes per-note
duration ms = wholenote/divider (negative divider = dotted *1.5, wholenote =
60000*4/tempo), and writes main/songs_generated.h as audio_note_t[] arrays +
a registry the firmware appends to its built-in songs.

Source: https://github.com/robsoncouto/arduino-songs (classic melodies).
Run: tools/gen_songs.py   (network required; writes the header)
Note durations are clamped and song length is bounded (MAX_NOTES) to keep the
compiled arrays small; verify song licenses before redistribution.
"""
from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "main" / "songs_generated.h"
RAW = "https://raw.githubusercontent.com/robsoncouto/arduino-songs/master/{s}/{s}.ino"

# (repo-slug, display name). Curated classic melodies; keep names <= ~16 chars
# so they fit the song-list buttons.
SONGS = [
    ("supermariobros", "Super Mario"),
    ("tetris",         "Tetris"),
    ("zeldaslullaby",  "Zelda Lullaby"),
    ("starwars",       "Star Wars"),
    ("pacman",         "Pac-Man"),
    ("pinkpanther",    "Pink Panther"),
    ("nokia",          "Nokia"),
    ("gameofthrones",  "GoT"),
    ("imperialmarch",  "Imperial March"),
    ("harrypotter",    "Harry Potter"),
    ("songofstorms",   "Song of Storms"),
    ("takeonme",       "Take On Me"),
    ("cantinaband",    "Cantina Band"),
    ("greensleeves",   "Greensleeves"),
    ("miichannel",     "Mii Channel"),
    ("nevergonnagiveyouup", "Never Gonna"),
    ("thegodfather",   "Godfather"),
    ("thelionsleepstonight", "Lion Sleeps"),
    ("startrekintro",  "Star Trek"),
    ("minuetg",        "Minuet in G"),
    ("silentnight",    "Silent Night"),
    ("merrychristmas", "Merry Xmas"),
    ("brahmslullaby",  "Brahms Lullaby"),
    ("vampirekiller",  "Vampire Killer"),
    ("bloodytears",    "Bloody Tears"),
    ("professorlayton","Prof Layton"),
]

MAX_NOTES = 220      # bound each array (keeps flash + play time sane)
MAX_MS = 2000        # clamp a single note duration


def fetch(slug: str) -> str:
    """Fetch a song's .ino source."""
    with urllib.request.urlopen(RAW.format(s=slug), timeout=20) as r:
        return r.read().decode("utf-8", "replace")


def parse(src: str) -> list[tuple[int, int]]:
    """Return [(freq_hz, ms), ...] from a song .ino."""
    defines = {m[1]: int(m[2]) for m in re.finditer(r"#define\s+(NOTE_\w+)\s+(\d+)", src)}
    defines["REST"] = 0
    tm = re.search(r"int\s+tempo\s*=\s*(\d+)", src)
    tempo = int(tm.group(1)) if tm else 120
    wholenote = (60000 * 4) // tempo
    # Extract the melody[] body.
    mm = re.search(r"int\s+melody\s*\[\]\s*=\s*\{(.*?)\};", src, re.S)
    if not mm:
        return []
    body = re.sub(r"//.*?$|/\*.*?\*/", "", mm.group(1), flags=re.S | re.M)
    toks = [t.strip() for t in body.split(",") if t.strip()]
    out: list[tuple[int, int]] = []
    for i in range(0, len(toks) - 1, 2):
        note_t, div_t = toks[i], toks[i + 1]
        freq = defines.get(note_t)
        if freq is None:
            # a bare number note (rare) or unknown -> skip the pair
            try:
                freq = int(note_t)
            except ValueError:
                continue
        try:
            divider = int(div_t)
        except ValueError:
            continue
        if divider > 0:
            ms = wholenote // divider
        else:
            ms = int((wholenote // -divider) * 1.5)   # dotted
        ms = max(1, min(ms, MAX_MS))
        out.append((freq, ms))
        if len(out) >= MAX_NOTES:
            break
    return out


def main() -> int:
    """Fetch + convert all SONGS and write the generated header."""
    arrays, registry = [], []
    for slug, name in SONGS:
        try:
            notes = parse(fetch(slug))
        except Exception as exc:  # network/parse — report, keep going
            print(f"  skip {slug}: {exc}", file=sys.stderr)
            continue
        if not notes:
            print(f"  skip {slug}: no notes parsed", file=sys.stderr)
            continue
        ident = "SONG_" + re.sub(r"[^A-Za-z0-9]", "_", slug).upper()
        rows = ", ".join(f"{{{f},{ms}}}" for f, ms in notes)
        arrays.append(f"static const audio_note_t {ident}[] = {{ {rows} }};")
        registry.append(f'    {{ "{name}", {ident}, sizeof({ident})/sizeof(audio_note_t) }},')
        print(f"  {name}: {len(notes)} notes")

    hdr = (
        "// GENERATED by tools/gen_songs.py from robsoncouto/arduino-songs.\n"
        "// DO NOT EDIT BY HAND — re-run the generator. Classic melodies as\n"
        "// note arrays (verify licenses before redistribution).\n"
        "#pragma once\n\n"
        + "\n".join(arrays)
        + "\n\n#define GENERATED_SONGS \\\n"
        + " \\\n".join(registry)
        + "\n"
    )
    HEADER.write_text(hdr)
    print(f"wrote {HEADER.relative_to(ROOT)} ({len(registry)} songs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
